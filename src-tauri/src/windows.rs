#![allow(dead_code)]
//! Session window manager: the shell-owned tab model for persea sessions.
//!
//! # Design (locked at planning time)
//!
//! The web client opens sessions via `window.open` and keeps them alive
//! server-side: a session page is a viewer over a server resource
//! (`/client/<session_id>`) and reconnects after transient disconnects
//! (1s/2s/4s backoff). The shell models each session as a TAB, and the
//! main window ("main") is a viewport that navigates between instance
//! pages and session pages. Switching tabs navigates the viewport to the
//! session's join URL; the server session survives the navigation.
//!
//! ## Tab strip: a dedicated shell window
//!
//! The locked design wants a browser-style strip across the top of the
//! main window. Constraints ruled out every in-window option:
//!
//! - The persea page sends `X-Frame-Options: DENY`, so the remote page
//!   cannot be embedded in a shell page (`<iframe>` is blocked).
//! - Windows keep native decorations (locked design), so there is no
//!   frameless titlebar area to host the strip.
//! - Tauri 2.11 has no stable multi-webview-per-window API, and the
//!   main window's webview occupies the whole window.
//!
//! The strip therefore lives in its own small shell window (`tabstrip`,
//! `shell/tabstrip.html`), docked to the main window's top edge: it
//! follows moves/resizes, hides when the main window is minimized,
//! maximized or fullscreen (a maximized window leaves no room above it),
//! hides in kiosk mode via [`set_strip_visible`], and shows only while
//! at least one session tab exists. Docking is best-effort on Wayland
//! (the compositor controls window positions; `set_position` is a no-op)
//! and documented as such.
//!
//! ## What the shell can and cannot observe
//!
//! The shell tracks tabs from what the webview surface exposes:
//! navigations, `window.open` requests, `window.close` attempts (via
//! page-initiated navigation away), the bridge `session-ready` /
//! `session-ended` events, document titles, and window lifecycle events.
//! It does NOT yet consume the paired API token (the pairing flow
//! stores tokens; a token accessor + sessions-API enrichment is a
//! follow-up), so the protocol badge and hostname metadata fields stay
//! `None` and the strip shows a generic badge; the data model carries
//! the fields so the sessions API can populate them once the accessor
//! exists. The document title ("entry — HH:MM:SS — ●") provides the
//! display label; the ticking duration is stripped.
//!
//! ## Session end and auto-close
//!
//! `session-ended` is the page's TERMINAL event (the web client never
//! emits it during its reconnect backoff). On it, the tab enters the
//! ended state and an auto-close timer fires after [`AUTO_CLOSE_SECS`];
//! the strip keeps the ended tab visible in the meantime so the user can
//! hit Reconnect. A reconnect (session-ready) or a manual close cancels
//! the effect. Transient disconnects never schedule anything.
//!
//! ## Terminate semantics (honest v1.2.0)
//!
//! Terminating a session server-side needs an authenticated
//! `DELETE /api/sessions/<id>`, which requires the paired API token
//! (the pairing flow stores one; the accessor is a follow-up).
//! Until then the tab menu's Terminate closes the tab view (the page's
//! own toolbar still terminates for real), and closing a tab never ends
//! the server-side session — exactly like closing a browser tab. The
//! sessions page shows the session and lets the user reconnect or
//! terminate it there.
//!
//! ## Wiring for the dispatcher (do not forget; this module does not
//! ## register itself)
//!
//! 1. `lib.rs` setup, in this order: build the main window (code-built),
//!    `bridge::register`, then `windows::setup(app)?`, then the
//!    auto-open call. `windows::setup` needs the main window to exist.
//! 2. Replace `navigation::lock_window_builder(builder, policy)` on the
//!    main window with `windows::lock_viewport_builder(builder,
//!    app.handle().clone())` (the manager rebuilds the navigation policy
//!    from the instance store at setup; the main window must not
//!    double-apply the plain handlers).
//! 3. Register the `cmd_tabs_*` / `cmd_monitors_*` commands in
//!    `tauri::generate_handler!`.
//! 4. `build.rs`: add the tab commands to the app-manifest command list
//!    (same pattern as the keyring commands). Without that they are
//!    allow-all, which violates the fail-closed rule for remote pages.
//! 5. `capabilities/default.json`: add `"tabstrip"` to `windows` (the
//!    strip page is a local page; without capability coverage its IPC is
//!    rejected wholesale) and add the autogenerated `allow-tabs-*` /
//!    `allow-monitors-*` permissions once step 4 lands.
//! 6. The main window must use the same per-instance webview data
//!    directory / store identifier as session windows, or popped-out
//!    sessions lose the login cookie. `windows::instance_webview_data`
//!    returns the canonical pair; apply it to the main window builder
//!    too.
//! 7. Session windows are built by this module with the same navigation
//!    lockdown the main window carries (the shared `NavigationPolicy`
//!    from the instance store), the bridge init script, the download
//!    handler and the per-instance data store. The lockdown handlers
//!    are this module's label-aware variants: the plain
//!    `navigation::*` handlers cannot report navigations into the tab
//!    manager, and session-window navigations drive tab lifecycle.

