/// The manager ties the pure state machine to the tauri runtime.
struct WindowManager {
    app: tauri::AppHandle,
    state: TabState,
    policy: NavigationPolicy,
    /// Shell-side strip override (kiosk mode hides the strip).
    strip_enabled: bool,
}

impl WindowManager {
    fn config_dir(&self) -> std::path::PathBuf {
        self.app
            .path()
            .app_config_dir()
            .unwrap_or_else(|_| std::env::temp_dir())
    }
}

fn manager() -> Option<std::sync::MutexGuard<'static, WindowManager>> {
    MANAGER.get().map(|m| m.lock().unwrap())
}

fn send(msg: Msg) -> Result<(), String> {
    let tx = TX
        .get()
        .ok_or_else(|| "window manager is not initialized".to_string())?;
    tx.send(msg)
        .map_err(|e| format!("window manager stopped: {e}"))
}

fn current_policy() -> NavigationPolicy {
    manager().map(|m| m.policy.clone()).unwrap_or_else(|| {
        let origins: Vec<String> = crate::instances::instances()
            .iter()
            .map(|i| i.url.clone())
            .collect();
        NavigationPolicy::new(origins, Vec::new())
    })
}

/// The canonical per-instance webview data directory + store identifier.
/// Session windows must share the instance's cookie store with the main
/// window, or popped sessions land on a login page. Apply the same pair
/// to the main window builder.
pub fn instance_webview_data(
    app: &tauri::AppHandle,
    instance_url: &str,
) -> (Option<[u8; 16]>, PathBuf) {
    let key = crate::instances::store_key(instance_url);
    let mut ident = [0u8; 16];
    for (i, b) in key.bytes().take(16).enumerate() {
        ident[i] = b;
    }
    let dir = app
        .path()
        .app_config_dir()
        .map(|d| d.join("stores").join(&key))
        .unwrap_or_else(|_| std::env::temp_dir().join("persea-stores").join(key));
    (Some(ident), dir)
}

/// Wire the viewport handlers onto the main window builder. Replaces
/// `navigation::lock_window_builder` for the main window; session
/// windows are built inside this module with the same handlers.
pub fn lock_viewport_builder<'a, R: Runtime, M: Manager<R>>(
    builder: WebviewWindowBuilder<'a, R, M>,
    app: tauri::AppHandle,
) -> WebviewWindowBuilder<'a, R, M> {
    builder
        .on_navigation(viewport_navigation_handler())
        .on_new_window(viewport_new_window_handler())
        .on_document_title_changed(title_handler())
        .on_download(crate::downloads::handler(app))
}

/// on_navigation for any window hosting persea pages: applies the
/// navigation lockdown and reports the navigation to the tab manager.
pub fn viewport_navigation_handler() -> impl Fn(&Url) -> bool + Send + 'static {
    navigation_handler_for(MAIN_WINDOW_LABEL.to_string())
}

fn navigation_handler_for(label: String) -> impl Fn(&Url) -> bool + Send + 'static {
    move |url: &Url| {
        let policy = current_policy();
        match policy.classify(url) {
            navigation::Decision::Allow => {}
            navigation::Decision::OpenExternally => {
                log_blocked(url);
                let _ = tauri_plugin_opener::open_url(url.as_str(), None::<&str>);
                return false;
            }
            navigation::Decision::Deny => {
                log_blocked(url);
                return false;
            }
        }
        if let Some(tx) = TX.get() {
            let _ = tx.send(Msg::Navigated {
                label: label.clone(),
                url: url.to_string(),
            });
        }
        true
    }
}

/// on_new_window: `window.open` from a persea page lands in the tab
/// manager (a new tab/window per the open mode), never in an unmanaged
/// default window (which would bypass the navigation lockdown).
pub fn viewport_new_window_handler<R: Runtime>(
) -> impl Fn(Url, NewWindowFeatures) -> NewWindowResponse<R> + Send + 'static {
    move |url: Url, _features: NewWindowFeatures| {
        if session_id_from_url(&url).is_some() {
            let _ = send(Msg::OpenSession {
                url: url.to_string(),
                mode: None,
            });
            return NewWindowResponse::Deny;
        }
        match current_policy().classify_new_window(&url) {
            navigation::Decision::Allow => {
                // Same-origin app page opened in a new window: the shell
                // is single-window, so open it in the viewport instead.
                let _ = send(Msg::Navigated {
                    label: MAIN_WINDOW_LABEL.to_string(),
                    url: url.to_string(),
                });
                let _ = send(Msg::DockNow);
                NewWindowResponse::Deny
            }
            navigation::Decision::OpenExternally => {
                let _ = tauri_plugin_opener::open_url(url.as_str(), None::<&str>);
                NewWindowResponse::Deny
            }
            navigation::Decision::Deny => NewWindowResponse::Deny,
        }
    }
}

/// on_document_title_changed for any window hosting persea pages.
pub fn title_handler<R: Runtime>() -> impl Fn(tauri::WebviewWindow<R>, String) + Send + 'static {
    move |win, title| {
        let label = win.label().to_string();
        let _ = send(Msg::TitleChanged { label, title });
    }
}

/// Build the shell tab strip window and start the manager worker.
/// Call once in the setup hook, AFTER the main window exists.
pub fn setup(app: &mut tauri::App) -> Result<(), Box<dyn std::error::Error>> {
    let config_dir = app.path().app_config_dir()?;
    std::fs::create_dir_all(&config_dir)?;
    let prefs = load_prefs(&config_dir);
    let (default_mode, overrides) = prefs_to_state(&prefs);
    let origins: Vec<String> = crate::instances::instances()
        .iter()
        .map(|i| i.url.clone())
        .collect();
    let policy = NavigationPolicy::new(origins.clone(), Vec::new());
    let mut state = TabState::new(default_mode);
    state.overrides = overrides;

    let app_handle = app.handle().clone();
    let _ = APP.set(app_handle.clone());
    let (tx, rx) = mpsc::channel::<Msg>();
    let _ = TX.set(tx.clone());

    let manager = WindowManager {
        app: app_handle.clone(),
        state,
        policy,
        strip_enabled: true,
    };
    let _ = MANAGER.set(Mutex::new(manager));

    // The strip window (hidden until the first tab exists; the dock
    // logic positions it above the main window).
    let builder = WebviewWindowBuilder::new(
        &app_handle,
        STRIP_WINDOW_LABEL,
        WebviewUrl::App("tabstrip.html".into()),
    )
    .title("Persea Tabs")
    .inner_size(STRIP_HEIGHT * 16.0, STRIP_HEIGHT)
    .visible(false)
    .focused(false)
    .decorations(false)
    .skip_taskbar(true)
    .resizable(false)
    .always_on_top(true);
    let strip = builder.build()?;
    let dock_tx = tx.clone();
    strip.on_window_event(move |event| {
        if let tauri::WindowEvent::CloseRequested { signal_tx, .. } = event {
            // Alt+F4 on the strip hides it; the dock logic re-shows it
            // when a tab exists and the main window is active.
            let _ = signal_tx.send(true);
            let _ = dock_tx.send(Msg::DockNow);
        }
    });
    strip.on_menu_event(move |_win, event| {
        let _ = handle_menu_event(&event);
    });

    // Bridge events: terminal session lifecycle. `session-ended` is the
    // page's terminal event (never emitted during reconnect backoff),
    // so ONLY this path schedules the auto-close.
    let ready_tx = tx.clone();
    app.listen_any("session-ready", move |event| {
        if let Some(id) = payload_session_id(event.payload()) {
            let _ = ready_tx.send(Msg::SessionReady { id });
        }
    });
    let ended_tx = tx.clone();
    app.listen_any("session-ended", move |event| {
        if let Some(id) = payload_session_id(event.payload()) {
            let _ = ended_tx.send(Msg::SessionEnded { id });
        }
    });

    // Global shortcut events: the hotkeys module emits a cycle-sessions
    // event (Ctrl+Shift+Tab chord, user-configurable) that the tab
    // manager consumes; the strip page handles Ctrl+Tab / Ctrl+Shift+Tab
    // locally while it has focus.
    let cycle_tx = tx.clone();
    app.listen_any(crate::hotkeys::EVENT_CYCLE_SESSIONS, move |_event| {
        let _ = cycle_tx.send(Msg::Next);
    });

    // The main window drives the strip's dock position.
    let move_tx = tx.clone();
    if let Some(main) = app_handle.get_webview_window(MAIN_WINDOW_LABEL) {
        main.on_window_event(move |event| match event {
            tauri::WindowEvent::Moved(_)
            | tauri::WindowEvent::Resized(_)
            | tauri::WindowEvent::ScaleFactorChanged { .. } => {
                let _ = move_tx.send(Msg::DockNow);
            }
            _ => {}
        });
    }

    std::thread::spawn(move || worker_loop(app_handle, rx));
    Ok(())
}

fn payload_session_id(payload: &str) -> Option<String> {
    serde_json::from_str::<serde_json::Value>(payload)
        .ok()
        .and_then(|v| {
            v.get("session_id")
                .and_then(|s| s.as_str())
                .map(str::to_string)
        })
}

/// Parse a tab context-menu id back into a manager message.
fn handle_menu_event(event: &tauri::menu::MenuEvent) -> Result<(), String> {
    let id = event.id().as_ref().to_string();
    if let Some(rest) = id.strip_prefix("tab-pop-out:") {
        return send(Msg::PopOut {
            id: rest.to_string(),
        });
    }
    if let Some(rest) = id.strip_prefix("tab-pop-in:") {
        return send(Msg::PopIn {
            id: rest.to_string(),
        });
    }
    if let Some(rest) = id.strip_prefix("tab-copy:") {
        return copy_share_link(rest);
    }
    if let Some(rest) = id.strip_prefix("tab-terminate:") {
        return send(Msg::Close {
            id: rest.to_string(),
        });
    }
    if let Some(rest) = id.strip_prefix("tab-expand:") {
        // tab-expand:<tab-id>|<monitor name>
        let (tab_id, monitor) = rest
            .split_once('|')
            .map(|(t, m)| (t.to_string(), Some(m.to_string())))
            .unwrap_or((rest.to_string(), None));
        return expand_on_monitor(tab_id, monitor);
    }
    Err(format!("unknown tab menu id {id:?}"))
}

fn copy_share_link(id: &str) -> Result<(), String> {
    let url = manager()
        .and_then(|m| {
            m.state
                .tabs()
                .iter()
                .find(|t| t.id == id)
                .map(|t| t.url.clone())
        })
        .ok_or_else(|| format!("no tab {id}"))?;
    let app = APP
        .get()
        .ok_or_else(|| "window manager is not initialized".to_string())?;
    use tauri_plugin_clipboard_manager::ClipboardExt;
    app.clipboard().write_text(url).map_err(|e| e.to_string())
}

fn expand_on_monitor(id: String, monitor: Option<String>) -> Result<(), String> {
    let app = APP
        .get()
        .ok_or_else(|| "window manager is not initialized".to_string())?;
    let main = app
        .get_webview_window(MAIN_WINDOW_LABEL)
        .ok_or_else(|| "main window not found".to_string())?;
    let monitors = main.available_monitors().map_err(|e| e.to_string())?;
    let chosen = monitor
        .as_ref()
        .and_then(|name| {
            monitors
                .iter()
                .find(|m| m.name().map(|n| n == name).unwrap_or(false))
        })
        .or_else(|| monitors.first());
    let Some(target) = chosen else {
        return Err("no display available".to_string());
    };
    let target = MonitorTarget {
        name: target.name().cloned(),
        x: target.position().x,
        y: target.position().y,
        width: target.size().width,
        height: target.size().height,
    };
    send(Msg::Expand { id, target })
}

