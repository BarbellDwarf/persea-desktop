/// Live / ended status of a session tab.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum TabStatus {
    /// Registered but no `session-ready` seen yet.
    Connecting,
    /// `session-ready` received (or re-received after a reconnect).
    Live,
    /// The page's terminal `session-ended` event arrived.
    Ended,
}

/// Where a tab's view lives.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TabMode {
    /// The main window viewport shows the session page.
    Inline,
    /// The session has its own native window (`session-<id>`).
    Popped,
    /// Fullscreen on a chosen monitor; `restore` says where it goes back.
    Expanded { restore: RestoreTarget },
}

/// Where an expanded tab returns on restore.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RestoreTarget {
    Inline,
    Popped,
}

/// Per-session / global open mode (locked design: tabs default).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum PopMode {
    /// Open inside the main window as a strip tab.
    Tabs,
    /// Open in its own native window.
    Window,
}

/// One session tab in the manager.
#[derive(Debug, Clone, PartialEq)]
pub struct Tab {
    pub id: String,
    /// Join URL (carries the share token when the page supplied one).
    pub url: String,
    /// Instance base URL (origin) this session belongs to.
    pub instance: String,
    /// Display label (document title, cleaned; fallback "Session <id>").
    pub title: String,
    /// Protocol badge; populated from the sessions API once a paired
    /// token exists (device pairing), `None` until then.
    pub protocol: Option<String>,
    /// Target hostname; same availability note as `protocol`.
    pub hostname: Option<String>,
    pub status: TabStatus,
    pub mode: TabMode,
    /// Monitor name when expanded fullscreen.
    pub monitor: Option<String>,
}

/// Serialized tab snapshot for the strip page.
#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct TabView {
    pub id: String,
    pub url: String,
    pub title: String,
    pub protocol: Option<String>,
    pub hostname: Option<String>,
    /// "connecting" | "live" | "ended"
    pub status: String,
    /// "inline" | "popped" | "expanded"
    pub mode: String,
    pub monitor: Option<String>,
    pub active: bool,
}

/// Monitor descriptor for the strip's expand submenu.
#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct MonitorView {
    pub name: String,
    pub width: u32,
    pub height: u32,
    pub x: i32,
    pub y: i32,
    pub scale_factor: f64,
}

/// Resolved expand target: monitor position + size in physical pixels.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MonitorTarget {
    pub name: Option<String>,
    pub x: i32,
    pub y: i32,
    pub width: u32,
    pub height: u32,
}

/// Side effects the state machine hands to the IO layer (the worker).
#[derive(Debug, Clone, PartialEq)]
pub enum Effect {
    /// Navigate the main window viewport (shell-initiated).
    NavigateViewport(String),
    FocusViewport,
    /// Build a `session-<id>` window for a tab.
    OpenSessionWindow {
        label: String,
        url: String,
        title: String,
        instance: String,
    },
    /// Destroy a window by label.
    CloseWindow(String),
    FocusWindow(String),
    SetTitle {
        label: String,
        title: String,
    },
    /// Move to the monitor and enter fullscreen.
    ExpandWindow {
        label: String,
        target: MonitorTarget,
    },
    UnfullscreenWindow(String),
    /// Recompute strip position/visibility.
    DockStrip,
    /// Tell the strip the tab list changed.
    EmitTabsChanged,
    /// Start the ended-state auto-close timer for a tab.
    AutoCloseScheduled(String),
    /// Persist the tab preferences file.
    SavePrefs,
    /// Hand a URL to the system browser.
    OpenExternal(String),
}

/// Messages the worker processes serially (single owner of effects).
#[derive(Debug, Clone)]
pub enum Msg {
    OpenSession { url: String, mode: Option<PopMode> },
    Switch { id: String },
    Close { id: String },
    Next,
    Prev,
    PopOut { id: String },
    PopIn { id: String },
    Expand { id: String, target: MonitorTarget },
    Restore { id: String },
    SetDefaultMode(PopMode),
    Navigated { label: String, url: String },
    SessionReady { id: String },
    SessionEnded { id: String },
    WindowClosed { label: String },
    WindowFocused { label: String },
    TitleChanged { label: String, title: String },
    AutoCloseTick { id: String },
    DockNow,
}

// ---------------------------------------------------------------------------
// Pure tab state machine (unit-testable without any tauri runtime)
// ---------------------------------------------------------------------------

#[derive(Debug, Default, Clone, PartialEq)]
pub struct TabState {
    tabs: Vec<Tab>,
    active: Option<String>,
    /// Last URL the main viewport settled on.
    viewport_url: Option<String>,
    /// Instance home (origin + "/") for viewport navigation targets.
    home: Option<String>,
    /// Shell-initiated viewport/window navigations that must NOT be
    /// interpreted as page-initiated departures.
    expected: HashSet<(String, String)>,
    default_mode: PopMode,
    /// Per-session open-mode overrides (persisted).
    overrides: HashMap<String, PopMode>,
}

impl TabState {
    pub fn new(default_mode: PopMode) -> Self {
        Self {
            default_mode,
            ..Self::default()
        }
    }

    pub fn tabs(&self) -> &[Tab] {
        &self.tabs
    }

    pub fn active(&self) -> Option<&str> {
        self.active.as_deref()
    }

    pub fn default_mode(&self) -> PopMode {
        self.default_mode
    }

    pub fn overrides(&self) -> &HashMap<String, PopMode> {
        &self.overrides
    }

    pub fn view(&self) -> Vec<TabView> {
        self.tabs
            .iter()
            .map(|t| TabView {
                id: t.id.clone(),
                url: t.url.clone(),
                title: t.title.clone(),
                protocol: t.protocol.clone(),
                hostname: t.hostname.clone(),
                status: match t.status {
                    TabStatus::Connecting => "connecting",
                    TabStatus::Live => "live",
                    TabStatus::Ended => "ended",
                }
                .to_string(),
                mode: match t.mode {
                    TabMode::Inline => "inline",
                    TabMode::Popped => "popped",
                    TabMode::Expanded { .. } => "expanded",
                }
                .to_string(),
                monitor: t.monitor.clone(),
                active: self.active.as_deref() == Some(t.id.as_str()),
            })
            .collect()
    }

    /// The main entry for opening a session (window.open, share links,
    /// shell "open" commands). Duplicate opens focus the existing tab.
    pub fn open_session(&mut self, url: &Url, mode: Option<PopMode>) -> Vec<Effect> {
        let Some(id) = session_id_from_url(url) else {
            return vec![Effect::OpenExternal(url.to_string())];
        };
        if let Some(tab) = self.tabs.iter_mut().find(|t| t.id == id) {
            tab.url = url.to_string();
            return self.switch(&id);
        }
        let mode = mode
            .or_else(|| self.overrides.get(&id).copied())
            .unwrap_or(self.default_mode);
        let instance = instance_origin(url);
        if self.home.is_none() {
            self.home = Some(instance.clone() + "/");
        }
        let title = format!("Session {}", short_id(&id));
        self.tabs.push(Tab {
            id: id.clone(),
            url: url.to_string(),
            instance,
            title,
            protocol: None,
            hostname: None,
            status: TabStatus::Connecting,
            mode: match mode {
                PopMode::Tabs => TabMode::Inline,
                PopMode::Window => TabMode::Popped,
            },
            monitor: None,
        });
        self.active = Some(id.clone());
        let mut effects = vec![Effect::EmitTabsChanged, Effect::DockStrip];
        match mode {
            PopMode::Tabs => {
                effects.push(Effect::NavigateViewport(url.to_string()));
                effects.push(Effect::FocusViewport);
            }
            PopMode::Window => {
                effects.push(Effect::OpenSessionWindow {
                    label: session_window_label(&id),
                    url: url.to_string(),
                    title: self.tabs.last().unwrap().title.clone(),
                    instance: self.tabs.last().unwrap().instance.clone(),
                });
                effects.push(Effect::FocusWindow(session_window_label(&id)));
            }
        }
        effects
    }

    /// Make a tab the active one, per its mode.
    pub fn switch(&mut self, id: &str) -> Vec<Effect> {
        let Some(idx) = self.tabs.iter().position(|t| t.id == id) else {
            return Vec::new();
        };
        let (mode, url) = {
            let tab = &self.tabs[idx];
            (tab.mode, tab.url.clone())
        };
        if self.active.as_deref() == Some(id) {
            // Duplicate-open on the active tab: re-assert the window so
            // the focus request is not lost, otherwise no-op.
            return match mode {
                TabMode::Popped | TabMode::Expanded { .. } => {
                    vec![Effect::FocusWindow(session_window_label(id))]
                }
                TabMode::Inline => Vec::new(),
            };
        }
        self.active = Some(id.to_string());
        match mode {
            TabMode::Inline => vec![
                Effect::NavigateViewport(url),
                Effect::FocusViewport,
                Effect::EmitTabsChanged,
            ],
            TabMode::Popped => vec![
                Effect::FocusWindow(session_window_label(id)),
                Effect::EmitTabsChanged,
            ],
            TabMode::Expanded { .. } => self.restore(id),
        }
    }

    pub fn next_tab(&mut self) -> Vec<Effect> {
        self.step_tab(1)
    }

    pub fn prev_tab(&mut self) -> Vec<Effect> {
        self.step_tab(-1)
    }

    fn step_tab(&mut self, step: isize) -> Vec<Effect> {
        if self.tabs.is_empty() {
            return Vec::new();
        }
        let cur = self
            .active
            .as_deref()
            .and_then(|a| self.tabs.iter().position(|t| t.id == a))
            .unwrap_or(0);
        let next = (cur as isize + step).rem_euclid(self.tabs.len() as isize) as usize;
        self.switch(&self.tabs[next].id.clone())
    }

    /// Close a tab. Manual close is always allowed; the server-side
    /// session is untouched (closing a browser tab never terminates it).
    pub fn close(&mut self, id: &str) -> Vec<Effect> {
        let Some(idx) = self.tabs.iter().position(|t| t.id == id) else {
            return Vec::new();
        };
        let was_active = self.active.as_deref() == Some(id);
        let was_inline = matches!(self.tabs[idx].mode, TabMode::Inline);
        let label = session_window_label(id);
        let mut effects = Vec::new();
        let previous = self.remove_tab_at(idx);
        if was_active {
            self.active = previous.clone();
        }
        if !was_inline {
            effects.push(Effect::CloseWindow(label));
        }
        if was_active && was_inline {
            let target = previous
                .as_ref()
                .and_then(|p| self.tabs.iter().find(|t| t.id == *p).map(|t| t.url.clone()))
                .unwrap_or_else(|| viewport_home(&self.tabs, &self.home));
            effects.push(Effect::NavigateViewport(target));
            effects.push(Effect::FocusViewport);
        }
        if was_active && !was_inline {
            effects.push(Effect::FocusViewport);
        }
        effects.push(Effect::EmitTabsChanged);
        effects.push(Effect::DockStrip);
        effects
    }

    /// Move an inline tab into its own window.
    pub fn pop_out(&mut self, id: &str) -> Vec<Effect> {
        let Some(idx) = self.tabs.iter().position(|t| t.id == id) else {
            return Vec::new();
        };
        if !matches!(self.tabs[idx].mode, TabMode::Inline) {
            return self.switch(id);
        }
        self.overrides.insert(id.to_string(), PopMode::Window);
        self.tabs[idx].mode = TabMode::Popped;
        self.tabs[idx].monitor = None;
        let was_active = self.active.as_deref() == Some(id);
        let url = self.tabs[idx].url.clone();
        let instance = self.tabs[idx].instance.clone();
        let title = self.tabs[idx].title.clone();
        let label = session_window_label(id);
        let mut effects = vec![
            Effect::OpenSessionWindow {
                label: label.clone(),
                url,
                title,
                instance,
            },
            Effect::FocusWindow(label),
            Effect::SavePrefs,
            Effect::EmitTabsChanged,
        ];
        if was_active {
            let home = viewport_home(&self.tabs, &self.home);
            self.expected
                .insert((MAIN_WINDOW_LABEL.to_string(), home.clone()));
            effects.push(Effect::NavigateViewport(home));
        }
        effects
    }

    /// Move a popped/expanded tab back into the viewport.
    pub fn pop_in(&mut self, id: &str) -> Vec<Effect> {
        let Some(idx) = self.tabs.iter().position(|t| t.id == id) else {
            return Vec::new();
        };
        match self.tabs[idx].mode {
            TabMode::Inline => return Vec::new(),
            TabMode::Popped | TabMode::Expanded { .. } => {}
        }
        self.overrides.insert(id.to_string(), PopMode::Tabs);
        self.tabs[idx].mode = TabMode::Inline;
        self.tabs[idx].monitor = None;
        let url = self.tabs[idx].url.clone();
        self.active = Some(id.to_string());
        vec![
            Effect::CloseWindow(session_window_label(id)),
            Effect::NavigateViewport(url),
            Effect::FocusViewport,
            Effect::SavePrefs,
            Effect::EmitTabsChanged,
            Effect::DockStrip,
        ]
    }

    /// Fullscreen the session on a user-chosen monitor.
    pub fn expand(&mut self, id: &str, target: MonitorTarget) -> Vec<Effect> {
        let Some(idx) = self.tabs.iter().position(|t| t.id == id) else {
            return Vec::new();
        };
        let label = session_window_label(id);
        let mut effects = Vec::new();
        match self.tabs[idx].mode {
            TabMode::Inline => {
                let was_active = self.active.as_deref() == Some(id);
                let url = self.tabs[idx].url.clone();
                let instance = self.tabs[idx].instance.clone();
                let title = self.tabs[idx].title.clone();
                self.tabs[idx].mode = TabMode::Expanded {
                    restore: RestoreTarget::Inline,
                };
                effects.push(Effect::OpenSessionWindow {
                    label: label.clone(),
                    url,
                    title,
                    instance,
                });
                if was_active {
                    let home = viewport_home(&self.tabs, &self.home);
                    self.expected
                        .insert((MAIN_WINDOW_LABEL.to_string(), home.clone()));
                    effects.push(Effect::NavigateViewport(home));
                }
            }
            TabMode::Popped => {
                self.tabs[idx].mode = TabMode::Expanded {
                    restore: RestoreTarget::Popped,
                };
            }
            TabMode::Expanded { .. } => {
                // Already expanded: move to the newly chosen monitor.
            }
        }
        self.tabs[idx].monitor = target.name.clone();
        effects.push(Effect::ExpandWindow { label, target });
        effects.push(Effect::FocusWindow(session_window_label(id)));
        effects.push(Effect::EmitTabsChanged);
        effects.push(Effect::DockStrip);
        effects
    }

    /// Restore an expanded tab to its pre-expansion mode.
    pub fn restore(&mut self, id: &str) -> Vec<Effect> {
        let Some(idx) = self.tabs.iter().position(|t| t.id == id) else {
            return Vec::new();
        };
        let restore = match self.tabs[idx].mode {
            TabMode::Expanded { restore } => restore,
            _ => return Vec::new(),
        };
        let label = session_window_label(id);
        self.tabs[idx].monitor = None;
        let mut effects = vec![Effect::UnfullscreenWindow(label.clone())];
        match restore {
            RestoreTarget::Inline => {
                self.tabs[idx].mode = TabMode::Inline;
                let url = self.tabs[idx].url.clone();
                self.active = Some(id.to_string());
                effects.push(Effect::CloseWindow(label));
                effects.push(Effect::NavigateViewport(url));
                effects.push(Effect::FocusViewport);
            }
            RestoreTarget::Popped => {
                self.tabs[idx].mode = TabMode::Popped;
                effects.push(Effect::FocusWindow(label));
            }
        }
        effects.push(Effect::EmitTabsChanged);
        effects.push(Effect::DockStrip);
        effects
    }

    pub fn set_default_mode(&mut self, mode: PopMode) -> Vec<Effect> {
        if self.default_mode == mode {
            return Vec::new();
        }
        self.default_mode = mode;
        vec![Effect::SavePrefs]
    }

    /// A webview navigation (main viewport or a session window) settled.
    pub fn note_navigated(&mut self, label: &str, url: &Url) -> Vec<Effect> {
        if self.expected.remove(&(label.to_string(), url.to_string())) {
            if label == MAIN_WINDOW_LABEL {
                self.viewport_url = Some(url.to_string());
            }
            return Vec::new();
        }
        if label == MAIN_WINDOW_LABEL {
            self.note_viewport_navigated(url)
        } else {
            self.note_session_window_navigated(label, url)
        }
    }

    fn note_viewport_navigated(&mut self, url: &Url) -> Vec<Effect> {
        let prev = self.viewport_url.clone();
        self.viewport_url = Some(url.to_string());
        if matches!(url.scheme(), "http" | "https") {
            self.home = Some(instance_origin(url) + "/");
        }
        if let Some(id) = session_id_from_url(url) {
            // Entering a session page.
            if let Some(idx) = self.tabs.iter().position(|t| t.id == id) {
                self.active = Some(id);
                if !matches!(self.tabs[idx].mode, TabMode::Inline) {
                    // The viewport now displays a session that had its own
                    // window; fold it back inline (the window close event
                    // no-ops because the mode is already Inline).
                    let label = session_window_label(&id);
                    self.tabs[idx].mode = TabMode::Inline;
                    self.tabs[idx].monitor = None;
                    return vec![
                        Effect::CloseWindow(label),
                        Effect::EmitTabsChanged,
                        Effect::DockStrip,
                    ];
                }
                return vec![Effect::EmitTabsChanged];
            }
            // Share-link join: the viewport navigated to a session we had
            // no tab for.
            return self.open_session(url, None);
        }
        // Leaving a session page by a page-initiated navigation (close
        // flow, logout, manual URL): the tab is a view, the view is gone.
        let Some(prev_id) = prev.as_deref().and_then(session_id_from_str) else {
            return Vec::new();
        };
        if let Some(idx) = self.tabs.iter().position(|t| t.id == prev_id) {
            let was_active = self.active.as_deref() == Some(prev_id.as_str());
            let previous = self.remove_tab_at(idx);
            if was_active {
                self.active = previous;
            }
            return vec![Effect::EmitTabsChanged, Effect::DockStrip];
        }
        Vec::new()
    }

    fn note_session_window_navigated(&mut self, label: &str, url: &Url) -> Vec<Effect> {
        let Some(id) = label.strip_prefix(SESSION_WINDOW_PREFIX) else {
            return Vec::new();
        };
        if let Some(new_id) = session_id_from_url(url) {
            if new_id == id {
                // The window loaded its own join URL: no-op.
                return Vec::new();
            }
            // Session-to-session navigation inside a pop-out window:
            // close this tab/window and open the new session per mode.
            let mut effects = self.close(id);
            effects.extend(self.open_session(url, None));
            return effects;
        }
        // Page-initiated departure (close flow, logout): the tab is a
        // view, the view is gone; close tab + window.
        self.close(id)
    }

    pub fn note_session_ready(&mut self, id: &str) -> Vec<Effect> {
        let Some(tab) = self.tabs.iter_mut().find(|t| t.id == id) else {
            return Vec::new();
        };
        match tab.status {
            TabStatus::Ended => Vec::new(),
            _ => {
                tab.status = TabStatus::Live;
                vec![Effect::EmitTabsChanged]
            }
        }
    }

    /// The page's terminal end event. Schedules the auto-close timer
    /// exactly once; transient disconnects never reach this path.
    pub fn note_session_ended(&mut self, id: &str) -> Vec<Effect> {
        let Some(tab) = self.tabs.iter_mut().find(|t| t.id == id) else {
            return Vec::new();
        };
        if tab.status == TabStatus::Ended {
            return Vec::new();
        }
        tab.status = TabStatus::Ended;
        vec![
            Effect::AutoCloseScheduled(id.to_string()),
            Effect::EmitTabsChanged,
        ]
    }

    pub fn note_window_closed(&mut self, label: &str) -> Vec<Effect> {
        let Some(id) = label.strip_prefix(SESSION_WINDOW_PREFIX) else {
            return Vec::new();
        };
        let Some(idx) = self.tabs.iter().position(|t| t.id == id) else {
            return Vec::new();
        };
        // Only windows that should still exist trigger a removal; a
        // shell-initiated inline fold already flipped the mode.
        if matches!(self.tabs[idx].mode, TabMode::Inline) {
            return Vec::new();
        }
        let was_active = self.active.as_deref() == Some(id);
        let previous = self.remove_tab_at(idx);
        if was_active {
            self.active = previous;
        }
        let mut effects = vec![Effect::EmitTabsChanged, Effect::DockStrip];
        if was_active {
            effects.push(Effect::FocusViewport);
        }
        effects
    }

    pub fn note_window_focused(&mut self, label: &str) -> Vec<Effect> {
        let Some(id) = label.strip_prefix(SESSION_WINDOW_PREFIX) else {
            // A non-session window took focus: no key injection target.
            crate::hooks::set_session_focus(false);
            return Vec::new();
        };
        if !self.tabs.iter().any(|t| t.id == id) {
            crate::hooks::set_session_focus(false);
            return Vec::new();
        }
        crate::hooks::set_session_focus(true);
        if self.active.as_deref() == Some(id) {
            return Vec::new();
        }
        self.active = Some(id.to_string());
        vec![Effect::EmitTabsChanged]
    }

    /// Document title → tab label. The page's live title ticks
    /// ("entry — HH:MM:SS — ●") is cleaned to its stable prefix so the
    /// strip does not re-render every second.
    pub fn note_title(&mut self, label: &str, title: &str) -> Vec<Effect> {
        let cleaned = clean_title(title);
        let id: Option<String> = if label == MAIN_WINDOW_LABEL {
            self.viewport_url.as_deref().and_then(session_id_from_str)
        } else {
            label
                .strip_prefix(SESSION_WINDOW_PREFIX)
                .map(str::to_string)
        };
        let Some(id) = id else { return Vec::new() };
        let Some(idx) = self.tabs.iter().position(|t| t.id == id) else {
            return Vec::new();
        };
        if self.tabs[idx].title == cleaned {
            return Vec::new();
        }
        self.tabs[idx].title = cleaned.clone();
        vec![
            Effect::SetTitle {
                label: label.to_string(),
                title: cleaned,
            },
            Effect::EmitTabsChanged,
        ]
    }

    /// Auto-close timer fired: close only if the tab is still in the
    /// ended state (reconnect, pop-out or manual close already cleared it).
    pub fn note_auto_close_tick(&mut self, id: &str) -> Vec<Effect> {
        let ended = self
            .tabs
            .iter()
            .find(|t| t.id == id)
            .map(|t| t.status == TabStatus::Ended)
            .unwrap_or(false);
        if ended {
            self.close(id)
        } else {
            Vec::new()
        }
    }

    /// Remove the tab at `idx` and return the id of the tab that takes
    /// over as active (the neighbor before it, else the one after).
    fn remove_tab_at(&mut self, idx: usize) -> Option<String> {
        let previous = self.previous_tab_of(idx);
        self.tabs.remove(idx);
        previous
    }

    fn previous_tab_of(&self, idx: usize) -> Option<String> {
        if idx > 0 {
            self.tabs.get(idx - 1).map(|t| t.id.clone())
        } else {
            self.tabs.get(idx + 1).map(|t| t.id.clone())
        }
    }
}

/// Strip docking math (pure). Positions the strip above the main window,
/// below it when there is no room above, hidden when neither fits.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DockPlacement {
    Above(tauri::PhysicalPosition<i32>),
    Below(tauri::PhysicalPosition<i32>),
    Hidden,
}

pub fn dock_placement(
    strip_w: u32,
    strip_h: u32,
    main_pos: tauri::PhysicalPosition<i32>,
    main_size: tauri::PhysicalSize<u32>,
    work: tauri::PhysicalRect<i32, u32>,
) -> DockPlacement {
    let sw = strip_w as i32;
    let sh = strip_h as i32;
    if sw >= work.size.width as i32 {
        // Strip wider than the work area: nothing sensible to do.
        return DockPlacement::Hidden;
    }
    let clamp_x = |x: i32| {
        x.clamp(
            work.position.x,
            work.position.x + work.size.width as i32 - sw,
        )
    };
    if main_pos.y >= work.position.y + sh {
        DockPlacement::Above(tauri::PhysicalPosition::new(
            clamp_x(main_pos.x),
            main_pos.y - sh,
        ))
    } else if main_pos.y + main_size.height as i32 + sh <= work.position.y + work.size.height as i32
    {
        DockPlacement::Below(tauri::PhysicalPosition::new(
            clamp_x(main_pos.x),
            main_pos.y + main_size.height as i32,
        ))
    } else {
        DockPlacement::Hidden
    }
}

