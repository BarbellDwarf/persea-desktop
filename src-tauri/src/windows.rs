/// Extract the session id from a join URL (`/client/<id>`).
pub fn session_id_from_url(url: &Url) -> Option<String> {
    let mut segs = url.path_segments()?;
    let mut prev: Option<&str> = None;
    for seg in segs {
        if prev == Some("client") && !seg.is_empty() {
            return Some(seg.to_string());
        }
        prev = Some(seg);
    }
    None
}

fn session_id_from_str(raw: &str) -> Option<String> {
    Url::parse(raw).ok().and_then(|u| session_id_from_url(&u))
}

/// Instance origin (`scheme://host[:port]`) for a session URL.
fn instance_origin(url: &Url) -> String {
    url.origin().ascii_serialization()
}

/// Viewport home: the origin of the last tab's instance, else the first
/// tab's instance, else the instance the viewport last settled on, else
/// an empty string (no-op navigation).
fn viewport_home(tabs: &[Tab], home: &Option<String>) -> String {
    tabs.last()
        .or_else(|| tabs.first())
        .map(|t| t.instance.clone())
        .or_else(|| home.clone())
        .unwrap_or_default()
}

/// Window label for a session (`session-<id>`), locked design.
pub fn session_window_label(id: &str) -> String {
    format!("{SESSION_WINDOW_PREFIX}{}", sanitize_label(id))
}

/// Keep labels tame: alphanumerics, `-` and `_` survive, the rest fold
/// into `-`, runs collapse.
fn sanitize_label(id: &str) -> String {
    let mut out = String::with_capacity(id.len());
    let mut prev_dash = false;
    for c in id.chars() {
        if c.is_ascii_alphanumeric() || c == '-' || c == '_' {
            out.push(c);
            prev_dash = false;
        } else if !prev_dash {
            out.push('-');
            prev_dash = true;
        }
    }
    out.trim_matches('-').to_string()
}

fn short_id(id: &str) -> String {
    let cleaned = sanitize_label(id);
    if cleaned.len() <= 8 {
        cleaned
    } else {
        cleaned[..8].to_string()
    }
}

/// Strip the ticking duration from the page's live document title:
/// `entry — HH:MM:SS — ●` → `entry`.
pub fn clean_title(title: &str) -> String {
    let trimmed = title.trim();
    let without_dot = trimmed.strip_suffix(" — ●").unwrap_or(trimmed);
    // " — HH:MM:SS — " separators: split at the LAST " — " pair.
    if let Some(idx) = without_dot.rfind(" — ") {
        let (head, tail) = without_dot.split_at(idx);
        let tail = &tail[3..];
        let looks_like_timer = tail.len() == 8
            && tail.as_bytes()[2] == b':'
            && tail.as_bytes()[5] == b':'
            && tail[..2].chars().all(|c| c.is_ascii_digit())
            && tail[3..5].chars().all(|c| c.is_ascii_digit())
            && tail[6..8].chars().all(|c| c.is_ascii_digit());
        if looks_like_timer {
            return head.trim().to_string();
        }
    }
    without_dot.trim().to_string()
}

